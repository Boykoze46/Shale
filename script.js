function translate(text) {
    if (currentLanguage !== 'kk') return text;
    return kk.categories[text] || (kk.items[text] ? kk.items[text][0] : text);
}
function translateDescription(name, description) {
    return currentLanguage === 'kk' && kk.items[name] ? kk.items[name][1] : description;
}
