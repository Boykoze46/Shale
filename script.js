function jumpToSection(event, catId) {
    event.preventDefault();
    const target = document.getElementById(`section-${catId}`);
    if (target) {
        const header = document.querySelector('header');
        const headerOffset = (header ? header.getBoundingClientRect().height : 135) + 8;
        const elementPosition = target.getBoundingClientRect().top;
        const offsetPosition = elementPosition + window.pageYOffset - headerOffset;

        window.scrollTo({
            top: offsetPosition,
            behavior: 'smooth'
        });

        target.classList.remove('target-highlight');
        void target.offsetWidth;
        target.classList.add('target-highlight');

        setActiveButton(catId);
    }
}

function setActiveButton(catId) {
    if (activeCatId === catId) return;
    activeCatId = catId;

    fullMenuData.forEach(cat => {
        const btn = document.getElementById(`btn-${cat.id}`);
        if (btn) {
            if (cat.id === catId) {
                btn.className = "px-3.5 py-1.5 rounded-full border text-xs md:text-sm font-medium whitespace-nowrap transition-all duration-200 flex items-center gap-1.5 shrink-0 cat-btn-active";
                btn.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
            } else {
                btn.className = "px-3.5 py-1.5 rounded-full border text-xs md:text-sm font-medium whitespace-nowrap transition-all duration-200 flex items-center gap-1.5 shrink-0 bg-[#fcf9f2] text-[#5c4738] border-[#d6c7b0] hover:border-[#3d2b1f] hover:text-[#3d2b1f]";
            }
        }
    });
}

function setupScrollSpy() {
    if (window.__shaleScrollSpyInitialized) return;
    window.__shaleScrollSpyInitialized = true;
    window.addEventListener('scroll', () => {
        const header = document.querySelector('header');
        const headerOffset = (header ? header.getBoundingClientRect().height : 160) + 8;
        let currentId = fullMenuData[0].id;

        fullMenuData.forEach(cat => {
            const section = document.getElementById(`section-${cat.id}`);
            if (section) {
                const top = section.getBoundingClientRect().top;
                if (top <= headerOffset) {
                    currentId = cat.id;
                }
            }
        });

        setActiveButton(currentId);
    });
}